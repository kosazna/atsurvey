#!/usr/bin/env bash
# Write .env (API) and web/.env.local (web app) from the running local Supabase stack.
# Usage: bash scripts/local-env.sh        (after `npx supabase start`)
set -euo pipefail
cd "$(dirname "$0")/.."
eval "$(npx --yes supabase@2 status -o env 2>/dev/null | grep -E '^(API_URL|ANON_KEY|JWT_SECRET)=')"
: "${API_URL:?local Supabase is not running — start it with: npx supabase start}"

cat > .env <<ENV
# Engine API — local development against the local Supabase stack (generated)
ENVIRONMENT=development
SUPABASE_URL=${API_URL}
SUPABASE_ANON_KEY=${ANON_KEY}
SUPABASE_JWT_SECRET=${JWT_SECRET}
CORS_ORIGINS=["http://localhost:5173","http://127.0.0.1:5173","http://localhost:4173"]
RATE_LIMIT_ENABLED=false
ENV

cat > web/.env.local <<ENV
# Web app — local development (generated by scripts/local-env.sh)
VITE_API_URL=http://localhost:8000
VITE_SUPABASE_URL=${API_URL}
VITE_SUPABASE_ANON_KEY=${ANON_KEY}
ENV
echo "wrote .env and web/.env.local (Supabase at ${API_URL})"
