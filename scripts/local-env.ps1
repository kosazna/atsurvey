# Windows PowerShell version of scripts/local-env.sh
# Usage: powershell -ExecutionPolicy Bypass -File scripts\local-env.ps1   (after `npx supabase start`)
$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")
$vars = @{}
npx --yes supabase@2 status -o env 2>$null | ForEach-Object {
  if ($_ -match '^(API_URL|ANON_KEY|JWT_SECRET)="?([^"]*)"?$') { $vars[$Matches[1]] = $Matches[2] }
}
if (-not $vars.API_URL) { throw "Local Supabase is not running - start it with: npx supabase start" }
@"
# Engine API - local development against the local Supabase stack (generated)
ENVIRONMENT=development
SUPABASE_URL=$($vars.API_URL)
SUPABASE_ANON_KEY=$($vars.ANON_KEY)
SUPABASE_JWT_SECRET=$($vars.JWT_SECRET)
CORS_ORIGINS=["http://localhost:5173","http://127.0.0.1:5173","http://localhost:4173"]
RATE_LIMIT_ENABLED=false
"@ | Set-Content -Encoding utf8 .env
@"
# Web app - local development (generated by scripts/local-env.ps1)
VITE_API_URL=http://localhost:8000
VITE_SUPABASE_URL=$($vars.API_URL)
VITE_SUPABASE_ANON_KEY=$($vars.ANON_KEY)
"@ | Set-Content -Encoding utf8 web\.env.local
Write-Host "wrote .env and web\.env.local (Supabase at $($vars.API_URL))"
